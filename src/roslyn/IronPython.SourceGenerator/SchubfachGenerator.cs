using System;
using System.Numerics;
using System.Text;

using Microsoft.CodeAnalysis;

namespace IronPython.SourceGenerator {
    [Generator(LanguageNames.CSharp)]
    public class SchubfachGenerator : IIncrementalGenerator {
        public void Initialize(IncrementalGeneratorInitializationContext context) {
            context.RegisterPostInitializationOutput(ctx => ctx.AddSource("Schubfach.pow10_significands.g.cs", Generate()));
        }

        private static string Generate() {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine();
            sb.AppendLine("namespace IronPython.Runtime {");
            sb.AppendLine("    internal static partial class Schubfach {");
            sb.AppendLine("        // 126-bit significands of overestimates of powers of 10.");
            sb.AppendLine("        // Generated with IronPython.SourceGenerator.SchubfachGenerator.");
            sb.AppendLine("        private static readonly ulong[] pow10_significands = [");

            // Range of decimal exponents [K_min, K_max] from the paper.
            const int dec_exp_min = -324;
            const int dec_exp_max = 292;

            const int num_bits = 126;

            // Negate dec_pow_min and dec_pow_max because we need negative powers 10^-k.
            for (int dec_exp = -dec_exp_max; dec_exp < -dec_exp_min + 1; dec_exp++) {
                // dec_exp is -k in the paper.
                int bin_exp = (int)Math.Floor(dec_exp * (Math.Log(10) / Math.Log(2))) - (num_bits - 1);
                BigInteger bin_pow = BigInteger.Pow(2, Math.Abs(bin_exp));
                BigInteger dec_pow = BigInteger.Pow(10, Math.Abs(dec_exp));
                BigInteger result;
                if (dec_exp < 0)
                    result = bin_pow / dec_pow;
                else if (bin_exp < 0)
                    result = dec_pow * bin_pow;
                else
                    result = dec_pow / bin_pow;
                result = result + 1;
                sb.AppendLine($"            0x{(ulong)(result >> 63):x}, 0x{(ulong)(result & (BigInteger.Pow(2, 63) - 1)):x16}, // {dec_exp,4}");
            }

            sb.AppendLine("        ];");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }
    }
}
